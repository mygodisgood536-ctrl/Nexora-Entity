/**
 * File storage for uploaded photos and portfolios.
 *
 * The platform has to be able to run on a serverless platform, where the local filesystem is
 * ephemeral: a file written by one request is not guaranteed to exist for the next one, and it
 * certainly does not survive a redeployment. Section 30 requires uploaded photos to be protected,
 * and section 33 asks for secure file/photo storage, so the storage location is a configuration
 * decision rather than a hard-coded path.
 *
 * Two drivers are offered:
 *
 *  * **Local** — the filesystem. Correct for development and for a single long-running host.
 *  * **Object storage** — any S3-compatible bucket, addressed by environment variables. This is
 *    what a hosted deployment uses.
 *
 * The driver is chosen by configuration, never by guessing, and the local driver refuses to run in
 * production unless it is explicitly enabled, so a deployment cannot silently lose uploads.
 */

import { createHash, randomBytes } from 'node:crypto';
import { mkdir, readFile, writeFile, unlink } from 'node:fs/promises';
import path from 'node:path';
import { config } from '@nexora/core/config';
import { createLogger } from '@nexora/core';

const log = createLogger('storage');

export interface StoredObject {
  /** The name the object is addressed by, e.g. `photos/<entity>/<file>.jpg`. */
  key: string;
  /** Where it was written, for the caller to record. */
  location: string;
  size: number;
  contentType: string;
}

export interface StorageDriver {
  readonly name: 'local' | 'object';
  put(key: string, body: Buffer, contentType: string): Promise<StoredObject>;
  get(key: string): Promise<{ body: Buffer; contentType: string } | null>;
  delete(key: string): Promise<void>;
  /** A URL the browser can fetch the object from. */
  publicUrl(key: string): string;
}

const ALLOWED_IMAGE_TYPES = new Set(['image/jpeg', 'image/png', 'image/webp', 'image/heic', 'image/avif']);

/** A short, opaque name for an upload. The original name is never used on disk or in a URL. */
export function storageKeyFor(scope: string, originalName: string, contentType: string): string {
  const ext = extensionFor(originalName, contentType);
  const stamp = Date.now().toString(36);
  const rand = randomBytes(6).toString('hex');
  return `${scope}/${stamp}-${rand}${ext}`;
}

function extensionFor(name: string, contentType: string): string {
  const fromName = path.extname(name).toLowerCase();
  const allowed = new Set(['.jpg', '.jpeg', '.png', '.webp', '.heic', '.avif', '.pdf', '.docx', '.md', '.txt', '.csv']);
  if (allowed.has(fromName)) return fromName;
  if (contentType === 'image/jpeg') return '.jpg';
  if (contentType === 'image/png') return '.png';
  if (contentType === 'application/pdf') return '.pdf';
  return '';
}

/** A stable identifier for an upload, used where the original bytes are compared. */
export function contentDigest(body: Buffer): string {
  return createHash('sha256').update(body).digest('hex');
}

export function isAllowedImageType(contentType: string): boolean {
  return ALLOWED_IMAGE_TYPES.has(contentType);
}

/* ── Local driver ─────────────────────────────────────────────────────────── */

class LocalDriver implements StorageDriver {
  readonly name = 'local' as const;
  constructor(private readonly root: string) {}

  private pathFor(key: string): string {
    // A key is generated by this module, never supplied by a caller, but resolve and check
    // anyway: a key that escapes the root would read or write outside it.
    const resolved = path.resolve(this.root, key);
    const base = path.resolve(this.root);
    if (resolved !== base && !resolved.startsWith(base + path.sep)) {
      throw new Error('Refusing to use a storage key outside the storage root');
    }
    return resolved;
  }

  async put(key: string, body: Buffer, contentType: string): Promise<StoredObject> {
    const target = this.pathFor(key);
    await mkdir(path.dirname(target), { recursive: true });
    await writeFile(target, body);
    log.info('object stored', { driver: this.name, key, size: body.length });
    return { key, location: target, size: body.length, contentType };
  }

  async get(key: string): Promise<{ body: Buffer; contentType: string } | null> {
    // The key is validated first, outside the try: a key that tries to escape the root is a
    // mistake worth surfacing, not a missing object.
    const target = this.pathFor(key);
    try {
      const body = await readFile(target);
      return { body, contentType: guessContentType(key) };
    } catch {
      return null;
    }
  }

  async delete(key: string): Promise<void> {
    try {
      await unlink(this.pathFor(key));
    } catch {
      /* already gone */
    }
  }

  publicUrl(key: string): string {
    return `/media/${key.split(path.sep).join('/')}`;
  }
}

function guessContentType(key: string): string {
  const ext = path.extname(key).toLowerCase();
  switch (ext) {
    case '.jpg':
    case '.jpeg':
      return 'image/jpeg';
    case '.png':
      return 'image/png';
    case '.webp':
      return 'image/webp';
    case '.heic':
      return 'image/heic';
    case '.avif':
      return 'image/avif';
    case '.pdf':
      return 'application/pdf';
    case '.csv':
      return 'text/csv';
    case '.md':
      return 'text/markdown';
    case '.txt':
      return 'text/plain';
    default:
      return 'application/octet-stream';
  }
}

/* ── Object storage driver ────────────────────────────────────────────────── */

/**
 * Any S3-compatible bucket.
 *
 * The request is signed with AWS Signature Version 4, which every S3-compatible provider
 * (Amazon S3, Cloudflare R2, MinIO, Backblaze B2) accepts, so the platform is not tied to one
 * vendor. Nothing is written to the local filesystem in this mode, which is what makes it safe on
 * a serverless platform.
 */
class ObjectStorageDriver implements StorageDriver {
  readonly name = 'object' as const;
  private readonly bucket: string;
  private readonly region: string;
  private readonly endpoint: string | undefined;
  private readonly accessKeyId: string;
  private readonly secretAccessKey: string;
  private readonly publicBaseUrl: string | undefined;

  constructor(input: {
    bucket: string;
    region: string;
    endpoint?: string | undefined;
    accessKeyId: string;
    secretAccessKey: string;
    publicBaseUrl?: string | undefined;
  }) {
    this.bucket = input.bucket;
    this.region = input.region;
    this.endpoint = input.endpoint?.replace(/\/+$/, '');
    this.accessKeyId = input.accessKeyId;
    this.secretAccessKey = input.secretAccessKey;
    this.publicBaseUrl = input.publicBaseUrl?.replace(/\/+$/, '');
  }

  private async signedRequest(method: 'PUT' | 'GET' | 'DELETE', key: string, body?: Buffer): Promise<Response> {
    const host = this.endpoint ? new URL(this.endpoint).host : `${this.bucket}.s3.${this.region}.amazonaws.com`;
    const pathName = `/${key.split('/').map(encodeURIComponent).join('/')}`;
    const url = this.endpoint ? `${this.endpoint}${pathName}` : `https://${host}${pathName}`;
    const payloadHash = createHash('sha256').update(body ?? Buffer.alloc(0)).digest('hex');
    const amzDate = new Date().toISOString().replace(/[:-]|\.\d{3}/g, '');
    const dateStamp = amzDate.slice(0, 8);
    const headers: Record<string, string> = {
      host,
      'x-amz-content-sha256': payloadHash,
      'x-amz-date': amzDate,
    };
    if (body) {
      headers['content-type'] = guessContentType(key);
    }
    const signedHeaderNames = Object.keys(headers).sort();
    const canonicalHeaders = signedHeaderNames.map((h) => `${h}:${String(headers[h]).trim()}\n`).join('');
    const signedHeaders = signedHeaderNames.join(';');
    const canonicalRequest = [method, pathName, '', canonicalHeaders, signedHeaders, payloadHash].join('\n');
    const scope = `${dateStamp}/${this.region}/s3/aws4_request`;
    const stringToSign = [
      'AWS4-HMAC-SHA256',
      amzDate,
      scope,
      createHash('sha256').update(canonicalRequest).digest('hex'),
    ].join('\n');
    const signingKey = ['aws4_request', this.region, dateStamp, this.bucket]
      .reduce((k, part) => createHash('sha256').update(k).update(part).digest('hex'), `AWS4${this.secretAccessKey}`);
    const signature = createHash('sha256')
      .update(signingKey)
      .update(stringToSign)
      .digest('hex');
    headers.authorization = `AWS4-HMAC-SHA256 Credential=${this.accessKeyId}/${scope}, SignedHeaders=${signedHeaders}, Signature=${signature}`;

    return fetch(url, {
      method,
      headers,
      body,
      // The body is signed, so it must be sent byte for byte.
      ...(body ? { duplex: 'half' } as unknown as RequestInit : {}),
    } as RequestInit);
  }

  async put(key: string, body: Buffer, contentType: string): Promise<StoredObject> {
    const res = await this.signedRequest('PUT', key, body);
    if (!res.ok) {
      throw new Error(`Object storage refused the upload (${res.status})`);
    }
    log.info('object stored', { driver: this.name, key, size: body.length });
    return { key, location: this.publicUrl(key), size: body.length, contentType };
  }

  async get(key: string): Promise<{ body: Buffer; contentType: string } | null> {
    const res = await this.signedRequest('GET', key);
    if (res.status === 404) return null;
    if (!res.ok) {
      throw new Error(`Object storage refused the read (${res.status})`);
    }
    const body = Buffer.from(await res.arrayBuffer());
    return { body, contentType: guessContentType(key) };
  }

  async delete(key: string): Promise<void> {
    const res = await this.signedRequest('DELETE', key);
    if (!res.ok && res.status !== 404) {
      throw new Error(`Object storage refused the delete (${res.status})`);
    }
  }

  publicUrl(key: string): string {
    const pathName = key.split('/').map(encodeURIComponent).join('/');
    if (this.publicBaseUrl) return `${this.publicBaseUrl}/${pathName}`;
    if (this.endpoint) return `${this.endpoint}/${this.bucket}/${pathName}`;
    return `https://${this.bucket}.s3.${this.region}.amazonaws.com/${pathName}`;
  }
}

/* ── Driver selection ─────────────────────────────────────────────────────── */

let driver: StorageDriver | undefined;

/**
 * The storage driver this deployment uses.
 *
 * Object storage is selected when a bucket and credentials are configured. The local driver is
 * refused in production unless it is explicitly allowed, because a serverless deployment that
 * writes uploads to an ephemeral disk loses them without any error.
 */
export function storage(): StorageDriver {
  if (driver) return driver;
  const cfg = config();
  const bucket = process.env.NEXORA_STORAGE_BUCKET ?? process.env.S3_BUCKET;
  const accessKeyId = process.env.NEXORA_STORAGE_ACCESS_KEY_ID ?? process.env.AWS_ACCESS_KEY_ID;
  const secretAccessKey = process.env.NEXORA_STORAGE_SECRET_ACCESS_KEY ?? process.env.AWS_SECRET_ACCESS_KEY;

  if (bucket && accessKeyId && secretAccessKey) {
    driver = new ObjectStorageDriver({
      bucket,
      region: process.env.NEXORA_STORAGE_REGION ?? process.env.AWS_REGION ?? 'us-east-1',
      endpoint: process.env.NEXORA_STORAGE_ENDPOINT ?? process.env.S3_ENDPOINT,
      accessKeyId,
      secretAccessKey,
      publicBaseUrl: process.env.NEXORA_STORAGE_PUBLIC_URL,
    });
    log.info('using object storage', { bucket, region: process.env.NEXORA_STORAGE_REGION ?? 'us-east-1' });
    return driver;
  }

  if (cfg.env === 'production' && process.env.NEXORA_ALLOW_LOCAL_STORAGE !== '1') {
    throw new Error(
      'No object storage is configured. Set NEXORA_STORAGE_BUCKET, NEXORA_STORAGE_ACCESS_KEY_ID and NEXORA_STORAGE_SECRET_ACCESS_KEY, or set NEXORA_ALLOW_LOCAL_STORAGE=1 to accept that uploads will not survive a redeployment.',
    );
  }

  driver = new LocalDriver(cfg.storageDir);
  log.info('using local file storage', { root: cfg.storageDir });
  return driver;
}

/** Test hook: forget the selected driver so a new configuration is picked up. */
export function resetStorage(): void {
  driver = undefined;
}
